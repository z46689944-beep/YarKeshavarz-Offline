function normalize(t=""){
  return String(t).toLowerCase()
    .replace(/[يى]/g,"ی")
    .replace(/ك/g,"ک")
    .replace(/\u200c/g," ")
    .replace(/[^\p{L}\p{N}\s]/gu," ")
    .replace(/\s+/g," ")
    .trim();
}

const aliasToName = {};
for(const [name,p] of Object.entries(profiles)){
  aliasToName[normalize(name)] = name;
  for(const a of (p.aliases||[])) aliasToName[normalize(a)] = name;
}

export function findCropProfile(name=""){
  return profiles[aliasToName[normalize(name)]] || null;
}

export function listCropProfiles(){
  return Object.keys(profiles);
}

export function profileFields(profile){
  if(!profile) return [];
  return Object.entries(profile)
    .filter(([k])=>!["aliases","category","scientificName","summary","sources","care","pests","diseases","risks"].includes(k))
    .map(([key,value])=>({key,value}));
}

